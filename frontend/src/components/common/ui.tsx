'use client';

import Link from 'next/link';
import { AlertTriangle, Inbox, Loader2, RefreshCw } from 'lucide-react';
import { Button } from '@/components/ui/button';
import { cn } from '@/lib/utils';
import type { Health, IncidentStatus, IncidentType, ObservationType } from '@/lib/types';

export function PageHeader({ title, description, actions }: { title: string; description?: React.ReactNode; actions?: React.ReactNode }) {
  return (
    <div className="mb-6 flex flex-col gap-3 sm:flex-row sm:items-start sm:justify-between">
      <div className="min-w-0">
        <h1 className="truncate text-2xl font-semibold tracking-tight">{title}</h1>
        {description && <p className="mt-1 text-sm text-muted-foreground">{description}</p>}
      </div>
      {actions && <div className="flex flex-wrap items-center gap-2">{actions}</div>}
    </div>
  );
}

export function Panel({ title, description, actions, children, className }: { title?: string; description?: React.ReactNode; actions?: React.ReactNode; children: React.ReactNode; className?: string }) {
  return (
    <section className={cn('rounded-xl border border-border bg-card text-card-foreground shadow-sm', className)}>
      {(title || actions) && (
        <header className="flex items-start justify-between gap-3 border-b border-border px-5 py-3.5">
          <div>
            {title && <h2 className="text-sm font-semibold">{title}</h2>}
            {description && <p className="mt-0.5 text-xs text-muted-foreground">{description}</p>}
          </div>
          {actions}
        </header>
      )}
      <div className="p-5">{children}</div>
    </section>
  );
}

export function StatCard({ label, value, hint, tone }: { label: string; value: React.ReactNode; hint?: string; tone?: 'ok' | 'warn' | 'bad' }) {
  return (
    <div className="rounded-xl border border-border bg-card p-4 shadow-sm">
      <p className="text-xs font-medium uppercase tracking-wide text-muted-foreground">{label}</p>
      <p className={cn('mt-1.5 text-2xl font-semibold tabular-nums', tone === 'ok' && 'text-ok', tone === 'warn' && 'text-warn', tone === 'bad' && 'text-bad')}>{value}</p>
      {hint && <p className="mt-1 text-xs text-muted-foreground">{hint}</p>}
    </div>
  );
}

const pill = 'inline-flex items-center gap-1.5 rounded-full border px-2.5 py-0.5 text-xs font-medium whitespace-nowrap';
const dot = 'h-1.5 w-1.5 rounded-full bg-current';

const HEALTH: Record<Health, { label: string; cls: string }> = {
  healthy: { label: 'Healthy', cls: 'border-ok/30 bg-ok/10 text-ok' },
  degraded: { label: 'Degraded', cls: 'border-warn/30 bg-warn/10 text-warn' },
  unavailable: { label: 'Unavailable', cls: 'border-bad/30 bg-bad/10 text-bad' },
  unknown: { label: 'No data yet', cls: 'border-border bg-muted text-muted-foreground' },
  paused: { label: 'Paused', cls: 'border-border bg-muted text-muted-foreground' },
};
export const HealthBadge = ({ health }: { health: Health }) => (
  <span className={cn(pill, HEALTH[health].cls)}><span className={dot} aria-hidden />{HEALTH[health].label}</span>
);

export const TypeBadge = ({ type }: { type: IncidentType }) => (
  <span className={cn(pill, type === 'AVAILABILITY' ? 'border-bad/30 bg-bad/10 text-bad' : 'border-warn/30 bg-warn/10 text-warn')}>
    {type === 'AVAILABILITY' ? 'Availability' : 'Latency'}
  </span>
);

export const StatusBadge = ({ status }: { status: IncidentStatus }) => (
  <span className={cn(pill, status === 'OPEN' ? 'border-bad/30 bg-bad/10 text-bad' : 'border-ok/30 bg-ok/10 text-ok')}>
    <span className={dot} aria-hidden />{status === 'OPEN' ? 'Open' : 'Resolved'}
  </span>
);

export const SimBadge = ({ type }: { type: ObservationType }) =>
  type === 'SIMULATED' ? <span className={cn(pill, 'border-sim/40 bg-sim/10 text-sim')} title="Generated by the demo simulator; no real endpoint was contacted">SIMULATED</span> : null;

export function ResultBadge({ success, code }: { success: boolean; code: number | null }) {
  return (
    <span className={cn(pill, success ? 'border-ok/30 bg-ok/10 text-ok' : 'border-bad/30 bg-bad/10 text-bad')}>
      {success ? 'OK' : 'Failed'}{code != null ? ` · ${code}` : ''}
    </span>
  );
}

export function Spinner({ label = 'Loading…' }: { label?: string }) {
  return (
    <div role="status" className="flex items-center justify-center gap-2 py-12 text-sm text-muted-foreground">
      <Loader2 className="h-4 w-4 animate-spin" aria-hidden />{label}
    </div>
  );
}

export function ErrorState({ message, onRetry }: { message: string; onRetry?: () => void }) {
  return (
    <div role="alert" className="flex flex-col items-center gap-3 rounded-xl border border-bad/30 bg-bad/5 px-6 py-10 text-center">
      <AlertTriangle className="h-6 w-6 text-bad" aria-hidden />
      <p className="max-w-md text-sm">{message}</p>
      {onRetry && <Button variant="outline" size="sm" onClick={onRetry}><RefreshCw className="mr-2 h-4 w-4" />Retry</Button>}
    </div>
  );
}

export function EmptyState({ title, description, action }: { title: string; description?: React.ReactNode; action?: { label: string; href: string } }) {
  return (
    <div className="flex flex-col items-center gap-2 px-6 py-12 text-center">
      <Inbox className="h-7 w-7 text-muted-foreground" aria-hidden />
      <p className="text-sm font-medium">{title}</p>
      {description && <p className="max-w-md text-sm text-muted-foreground">{description}</p>}
      {action && <Button asChild size="sm" className="mt-2"><Link href={action.href}>{action.label}</Link></Button>}
    </div>
  );
}

export function Pagination({ page, limit, total, onPage }: { page: number; limit: number; total: number; onPage: (p: number) => void }) {
  const pages = Math.max(1, Math.ceil(total / limit));
  if (total <= limit) return null;
  return (
    <nav aria-label="Pagination" className="flex items-center justify-between gap-3 pt-4 text-sm text-muted-foreground">
      <span>Page {page} of {pages} · {total} total</span>
      <span className="flex gap-2">
        <Button variant="outline" size="sm" disabled={page <= 1} onClick={() => onPage(page - 1)}>Previous</Button>
        <Button variant="outline" size="sm" disabled={page >= pages} onClick={() => onPage(page + 1)}>Next</Button>
      </span>
    </nav>
  );
}

